// Contract generation (ADR-008): the API's OpenAPI document → committed `openapi.json` + TypeScript types
// for the typed client (openapi-typescript). `--check` fails when the committed files differ.
import { spawnSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
export const CONTRACTS_ROOT = resolve(here, "..");
export const REPO_ROOT = resolve(CONTRACTS_ROOT, "../..");
/** Generated files live here (relative to packages/contracts). Never edit them by hand. */
export const OUTPUT_DIR = "src/openapi";

export interface Artifact {
  /** Path relative to packages/contracts. */
  path: string;
  content: string;
}

const TS_HEADER = "// Generated by `pnpm contracts:gen` from the API's OpenAPI document. Do not edit.\n";

/** Runs apps/api's exporter and returns its OpenAPI document. No DB or network is needed. */
export function readApiDocument(): OpenAPI3 {
  const apiDir = join(REPO_ROOT, "apps/api");
  const result = spawnSync(process.execPath, ["--import", "tsx", "src/lib/openapi-print.ts"], {
    cwd: apiDir,
    encoding: "utf8",
    env: { ...process.env, LOG_LEVEL: "silent" },
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0) {
    throw new Error(`apps/api openapi export failed (exit ${result.status}):\n${result.stderr}`);
  }
  return JSON.parse(result.stdout) as OpenAPI3;
}

async function pretty(content: string, path: string): Promise<string> {
  const filepath = join(CONTRACTS_ROOT, path);
  const config = (await resolveConfig(filepath)) ?? {};
  return format(content, { ...config, filepath });
}

/** Renders every generated file for `doc`, formatted with the repo's Prettier config. */
export async function generateArtifacts(doc: OpenAPI3): Promise<Artifact[]> {
  const jsonPath = `${OUTPUT_DIR}/openapi.json`;
  const typesPath = `${OUTPUT_DIR}/schema.ts`;
  const types = astToString(await openapiTS(doc, { alphabetize: false }));
  return [
    { path: jsonPath, content: await pretty(JSON.stringify(doc), jsonPath) },
    { path: typesPath, content: await pretty(`${TS_HEADER}\n${types}`, typesPath) },
  ];
}

/** Paths (relative to `root`) whose content on disk differs from the artifact, or that are missing. */
export async function findDrift(
  artifacts: readonly Artifact[],
  root: string = CONTRACTS_ROOT,
): Promise<string[]> {
  const drifted: string[] = [];
  for (const artifact of artifacts) {
    const current = await readFile(join(root, artifact.path), "utf8").catch(() => null);
    if (current !== artifact.content) drifted.push(artifact.path);
  }
  return drifted;
}
