import { spawnSync } from "node:child_process";
import { cp, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { OpenAPI3 } from "openapi-typescript";
import { afterAll, describe, expect, it } from "vitest";
import { CONTRACTS_ROOT, findDrift, generateArtifacts, OUTPUT_DIR } from "./generate";

const SAMPLE: OpenAPI3 = {
  openapi: "3.1.0",
  info: { title: "t", version: "1" },
  paths: {
    "/v1/things": {
      get: {
        responses: {
          200: {
            description: "ok",
            content: {
              "application/json": { schema: { type: "object", properties: { n: { type: "integer" } } } },
            },
          },
        },
      },
    },
  },
};

const temps: string[] = [];
async function tempCopy(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "mp-contracts-"));
  temps.push(dir);
  await cp(join(CONTRACTS_ROOT, OUTPUT_DIR), join(dir, OUTPUT_DIR), { recursive: true });
  return dir;
}
afterAll(async () => {
  await Promise.all(temps.map((d) => rm(d, { recursive: true, force: true })));
});

function runGen(args: string[]) {
  return spawnSync(process.execPath, ["--import", "tsx", "scripts/gen.ts", ...args], {
    cwd: CONTRACTS_ROOT,
    encoding: "utf8",
  });
}

describe("contract generation", () => {
  it("renders the document and client types deterministically", async () => {
    const a = await generateArtifacts(SAMPLE);
    const b = await generateArtifacts(SAMPLE);
    expect(a).toEqual(b);
    expect(a.map((x) => x.path)).toEqual([`${OUTPUT_DIR}/openapi.json`, `${OUTPUT_DIR}/schema.ts`]);
    expect(JSON.parse(a[0]!.content)).toEqual(SAMPLE);
    expect(a[1]!.content).toContain('"/v1/things"');
    expect(a[1]!.content.startsWith("// Generated by `pnpm contracts:gen`")).toBe(true);
  });

  it("findDrift reports changed and missing files only", async () => {
    const dir = await mkdtemp(join(tmpdir(), "mp-contracts-"));
    temps.push(dir);
    const artifacts = await generateArtifacts(SAMPLE);
    expect(await findDrift(artifacts, dir)).toEqual(artifacts.map((x) => x.path));
    await cp(join(CONTRACTS_ROOT, OUTPUT_DIR), join(dir, OUTPUT_DIR), { recursive: true });
    for (const artifact of artifacts) await writeFile(join(dir, artifact.path), artifact.content);
    expect(await findDrift(artifacts, dir)).toEqual([]);
    await writeFile(join(dir, artifacts[1]!.path), `${artifacts[1]!.content}// edited\n`);
    expect(await findDrift(artifacts, dir)).toEqual([artifacts[1]!.path]);
  });
});

describe("pnpm contracts:gen --check (WP-08 acceptance: CI fails on drift)", () => {
  it("passes when the committed client matches the API", () => {
    const res = runGen(["--check"]);
    expect(res.stderr).toBe("");
    expect(res.status).toBe(0);
  }, 60_000);

  it("fails when the committed client differs from generated output", async () => {
    const dir = await tempCopy();
    const schema = join(dir, OUTPUT_DIR, "schema.ts");
    await writeFile(schema, (await readFile(schema, "utf8")).replace('status: "ok"', 'status: "okay"'));
    const res = runGen(["--check", "--root", dir]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain("schema.ts");
    expect(res.stderr).toContain("pnpm contracts:gen");
  }, 60_000);

  it("fails when the committed OpenAPI document is missing, and regenerating fixes it", async () => {
    const dir = await tempCopy();
    await rm(join(dir, OUTPUT_DIR, "openapi.json"));
    expect(runGen(["--check", "--root", dir]).status).toBe(1);
    expect(runGen(["--root", dir]).status).toBe(0);
    expect(runGen(["--check", "--root", dir]).status).toBe(0);
  }, 90_000);
});
